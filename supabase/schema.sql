create table if not exists public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  email text unique not null,
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.users (id, email)
  values (new.id, lower(new.email))
  on conflict (id) do update set email = excluded.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert or update of email on auth.users
  for each row execute procedure public.handle_new_user();

create table if not exists public.contacts (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references public.users(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 1 and 120),
  organization text check (organization is null or char_length(organization) <= 160),
  role text check (role is null or char_length(role) <= 160),
  how_met text check (how_met is null or char_length(how_met) <= 300),
  met_on date,
  notes text check (notes is null or char_length(notes) <= 2000),
  next_follow_up_on date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.interactions (
  id bigint generated by default as identity primary key,
  contact_id bigint not null references public.contacts(id) on delete cascade,
  interaction_type text not null check (interaction_type in ('Meeting','Coffee chat','Call','Message','Email','Event','Other')),
  occurred_on date not null check (occurred_on <= current_date),
  notes text check (notes is null or char_length(notes) <= 2000),
  created_at timestamptz not null default now()
);

create table if not exists public.stars (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references public.users(id) on delete cascade,
  contact_id bigint not null references public.contacts(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (user_id, contact_id)
);

create table if not exists public.tags (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references public.users(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 1 and 30)
);
create unique index if not exists tags_user_name_unique
  on public.tags (user_id, lower(name));

create table if not exists public.contact_tags (
  contact_id bigint not null references public.contacts(id) on delete cascade,
  tag_id bigint not null references public.tags(id) on delete cascade,
  primary key (contact_id, tag_id)
);

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;
drop trigger if exists contacts_set_updated_at on public.contacts;
create trigger contacts_set_updated_at before update on public.contacts
  for each row execute procedure public.set_updated_at();

alter table public.users enable row level security;
alter table public.contacts enable row level security;
alter table public.interactions enable row level security;
alter table public.stars enable row level security;
alter table public.tags enable row level security;
alter table public.contact_tags enable row level security;

drop policy if exists "users read themselves" on public.users;
create policy "users read themselves" on public.users for select
  using (id = auth.uid());

drop policy if exists "users own contacts" on public.contacts;
create policy "users own contacts" on public.contacts for all
  using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists "users own interactions" on public.interactions;
create policy "users own interactions" on public.interactions for all
  using (exists (select 1 from public.contacts c where c.id = contact_id and c.user_id = auth.uid()))
  with check (exists (select 1 from public.contacts c where c.id = contact_id and c.user_id = auth.uid()));

drop policy if exists "users own stars" on public.stars;
create policy "users own stars" on public.stars for all
  using (user_id = auth.uid() and exists (select 1 from public.contacts c where c.id = contact_id and c.user_id = auth.uid()))
  with check (user_id = auth.uid() and exists (select 1 from public.contacts c where c.id = contact_id and c.user_id = auth.uid()));

drop policy if exists "users own tags" on public.tags;
create policy "users own tags" on public.tags for all
  using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists "users own contact tags" on public.contact_tags;
create policy "users own contact tags" on public.contact_tags for all
  using (
    exists (select 1 from public.contacts c where c.id = contact_id and c.user_id = auth.uid())
    and exists (select 1 from public.tags t where t.id = tag_id and t.user_id = auth.uid())
  )
  with check (
    exists (select 1 from public.contacts c where c.id = contact_id and c.user_id = auth.uid())
    and exists (select 1 from public.tags t where t.id = tag_id and t.user_id = auth.uid())
  );

create or replace function public.set_contact_tags(target_contact_id bigint, target_tag_ids bigint[])
returns setof public.tags
language plpgsql
security invoker
set search_path = public
as $$
begin
  if not exists (
    select 1 from public.contacts
    where id = target_contact_id and user_id = auth.uid()
  ) then
    raise exception 'Contact not found';
  end if;

  if exists (
    select 1 from unnest(coalesce(target_tag_ids, array[]::bigint[])) requested(id)
    where not exists (
      select 1 from public.tags
      where tags.id = requested.id and tags.user_id = auth.uid()
    )
  ) then
    raise exception 'Invalid tag';
  end if;

  delete from public.contact_tags where contact_id = target_contact_id;
  insert into public.contact_tags (contact_id, tag_id)
    select target_contact_id, requested.id
    from unnest(coalesce(target_tag_ids, array[]::bigint[])) requested(id)
    on conflict do nothing;

  return query
    select t.* from public.tags t
    where t.id = any(coalesce(target_tag_ids, array[]::bigint[]))
      and t.user_id = auth.uid()
    order by t.name;
end;
$$;

grant execute on function public.set_contact_tags(bigint, bigint[]) to authenticated;
